using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace CleanArch.Generators;

/// <summary>
/// Emits an AddGeneratedServices() extension registering every class
/// marked [AutoRegister] — conventions-over-config DI.
/// </summary>
[Generator]
public sealed class DIRegistrationGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        context.RegisterPostInitializationOutput(static ctx =>
            ctx.AddSource("AutoRegisterAttribute.g.cs",
                SourceText.From("""
                    // <auto-generated/>
                    namespace CleanArch.Generators;

                    public enum ServiceLifetimeKind { Singleton, Scoped, Transient }

                    [System.AttributeUsage(System.AttributeTargets.Class)]
                    public sealed class AutoRegisterAttribute(
                        ServiceLifetimeKind lifetime = ServiceLifetimeKind.Scoped)
                        : System.Attribute
                    {
                        public ServiceLifetimeKind Lifetime { get; } = lifetime;
                    }
                    """, Encoding.UTF8)));

        var classes = context.SyntaxProvider
            .ForAttributeWithMetadataName(
                "CleanArch.Generators.AutoRegisterAttribute",
                static (node, _) => node is ClassDeclarationSyntax,
                static (ctx, _) =>
                {
                    var decl = (ClassDeclarationSyntax)ctx.TargetNode;
                    var symbol =
                        (INamedTypeSymbol)ctx.SemanticModel
                            .GetDeclaredSymbol(decl)!;
                    var lifetime = ctx.Attributes
                        .SelectMany(a => a.ConstructorArguments)
                        .Select(a => a.Value?.ToString() ?? "Scoped")
                        .FirstOrDefault() ?? "Scoped";
                    return (Symbol: symbol, Lifetime: lifetime);
                })
            .Collect();

        context.RegisterSourceOutput(classes, static (spc, items) =>
        {
            if (items.IsDefaultOrEmpty) return;

            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated/>");
            sb.AppendLine("#nullable enable");
            sb.AppendLine(
                "namespace CleanArch.Generated;");
            sb.AppendLine();
            sb.AppendLine(
                "public static class GeneratedServiceRegistration");
            sb.AppendLine("{");
            sb.AppendLine(
                "    public static Microsoft.Extensions.DependencyInjection.IServiceCollection AddGeneratedServices(");
            sb.AppendLine(
                "        this Microsoft.Extensions.DependencyInjection.IServiceCollection services)");
            sb.AppendLine("    {");

            foreach (var (symbol, lifetime) in items)
            {
                var type = symbol.ToDisplayString(
                    SymbolDisplayFormat.FullyQualifiedFormat);
                var method = lifetime switch
                {
                    var l when l.Contains("Singleton") => "AddSingleton",
                    var l when l.Contains("Transient") => "AddTransient",
                    _ => "AddScoped"
                };
                sb.AppendLine(
                    $"        services.{method}<{type}>();");
            }

            sb.AppendLine("        return services;");
            sb.AppendLine("    }");
            sb.AppendLine("}");

            spc.AddSource("GeneratedServiceRegistration.g.cs",
                SourceText.From(sb.ToString(), Encoding.UTF8));
        });
    }
}
